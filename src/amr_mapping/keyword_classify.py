"""เดา TSIC division คร่าวๆ จาก "คำสำคัญ" ในข้อความอิสระภาษาไทย (เช่น สรุปจาก Wikipedia หรือ
"หมวดธุรกิจ" จาก dataforthai.com) — ใช้ตอนไม่มีรหัส TSIC จริงติดมาด้วยเลย (ต่างจาก dbd_lookup.py/
dbd_opendata.py ที่มีรหัส TSIC จริงจาก DBD ให้ใช้โดยตรง)

⚠️ นี่คือการจับคู่คำสำคัญแบบตรงตัว (substring match) ธรรมดา ไม่ใช่ AI/NLP ใดๆ ทั้งสิ้น — แม่นยำ
น้อยกว่ารหัส TSIC จริงมาก และมีโอกาสเดาผิดได้ถ้าข้อความมีคำกำกวม/หลายธุรกิจปนกัน ผู้เรียกต้องแสดง
ผลลัพธ์นี้ให้ผู้ใช้เห็นชัดเจนเสมอว่าเป็นการ "เดาจากคำสำคัญ" ไม่ใช่ข้อมูลทางการ (ดู
suggested_is_approximate/guessed_keyword ที่ web/app.py ใส่เพิ่มเข้าไปในผลลัพธ์)

รายการคำสำคัญเรียงจากเจาะจงที่สุดไปกว้างที่สุด (เช่นเช็ค "ร้านอาหาร" ก่อน "ร้าน" เฉยๆ) เพื่อลด
โอกาสจับคำกว้างเกินไปก่อนคำที่เจาะจงกว่า — เช็คทีละคำตามลำดับ คืนคำแรกที่เจอในข้อความ"""

from __future__ import annotations

from typing import List, Optional, Tuple

# (คำสำคัญ, TSIC division code) — division code อิงตาม TSIC/ISIC Rev.4 มาตรฐานเดียวกับที่ใช้ใน
# clustering._TSIC_SECTIONS และ dbd_opendata.py (รหัสวัตถุประสงค์ 2 หลักแรก)
_KEYWORD_TO_DIVISION: List[Tuple[str, str]] = [
    ("ร้านสะดวกซื้อ", "47"),
    ("มินิมาร์ท", "47"),
    ("ซูเปอร์มาร์เก็ต", "47"),
    ("ห้างสรรพสินค้า", "47"),
    ("ศูนย์การค้า", "47"),
    ("ค้าปลีก", "47"),
    ("ค้าส่ง", "46"),
    ("ตัวแทนจำหน่าย", "46"),
    ("ร้านอาหาร", "56"),
    ("ภัตตาคาร", "56"),
    ("โรงแรม", "55"),
    ("รีสอร์ท", "55"),
    ("โรงพยาบาล", "86"),
    ("สถานพยาบาล", "86"),
    ("คลินิก", "86"),
    ("ธนาคาร", "64"),
    ("สถาบันการเงิน", "64"),
    ("ประกันภัย", "65"),
    ("ประกันชีวิต", "65"),
    ("อสังหาริมทรัพย์", "68"),
    ("ให้เช่าอาคาร", "68"),
    ("ก่อสร้าง", "41"),
    ("รับเหมาก่อสร้าง", "41"),
    ("ขนส่งสินค้า", "49"),
    ("โลจิสติกส์", "52"),
    ("โทรคมนาคม", "61"),
    # ตั้งใจไม่ใส่คำกว้างๆ อย่าง "โรงงาน"/"โรงงานอุตสาหกรรม" ไว้ที่นี่ — ลองแมปไปที่ division ของ
    # หมวดการผลิตดูแล้วพบว่าบังเอิญมีธุรกิจที่มีโปรไฟล์จริงเจาะจงมากอยู่ใน division นั้น (เช่น
    # division "10" ตรงกับ "การผลิตน้ำแข็ง" พอดีในข้อมูลตอนนี้) ทำให้เดาผิดแบบเจาะจงเกินจริงได้
    # (เช่น เจอคำว่า "โรงงาน" กว้างๆ แล้วดันเสนอ "การผลิตน้ำแข็ง" ซึ่งไม่เกี่ยวกันเลย) ต่างจากคำอื่น
    # ในลิสต์นี้ที่ต่อให้ไม่มีธุรกิจ TSIC division เดียวกันเป๊ะ ระบบจะ fallback ไปใช้ธุรกิจ section
    # เดียวกัน/ตัวแทนกลุ่มรูปแบบการใช้ไฟแทนอย่างสมเหตุสมผล (ดู nearest_business_type_by_tsic)
]


def guess_tsic_division(text: str) -> Optional[Tuple[str, str]]:
    """สแกนหาคำสำคัญแรกที่เจอในข้อความ (ไม่สนตัวพิมพ์ใหญ่เล็ก แม้ภาษาไทยไม่มีอยู่แล้วก็ตาม)
    คืน (division_code, matched_keyword) หรือ None ถ้าไม่เจอคำสำคัญที่รู้จักเลย"""

    if not text:
        return None
    for keyword, division_code in _KEYWORD_TO_DIVISION:
        if keyword in text:
            return (division_code, keyword)
    return None
